#pragma once
#include "NLPSolverBase.h"

#include <variant>

namespace SHOT
{
class Solver;

class NLPSolverSHOT : public NLPSolverBase
{
private:
    ProblemPtr sourceProblem;
    ProblemPtr relaxedProblem;

    VectorInteger fixedVariableIndexes;
    VectorDouble fixedVariableValues;

    // The variable bounds and the settings given to this object, which are also used in the nested solvers created
    // for later solves
    VectorDouble variableLowerBounds;
    VectorDouble variableUpperBounds;
    std::vector<std::pair<std::string, std::variant<int, double, bool>>> settingUpdates;

    bool problemInfoPrinted = false;

    // Whether the current nested solver has been used, in which case a new one is created for the next solve
    bool isNestedSolverUsed = false;

    void initializeMIPProblem();

public:
    NLPSolverSHOT(EnvironmentPtr envPtr, ProblemPtr source);

    ~NLPSolverSHOT() override;

    void setStartingPoint(VectorInteger variableIndexes, VectorDouble variableValues) override;
    void clearStartingPoint() override;

    void fixVariables(VectorInteger variableIndexes, VectorDouble variableValues) override;

    void unfixVariables() override;

    void saveOptionsToFile(std::string fileName) override;

    void saveProblemToFile(std::string fileName) override;

    VectorDouble getSolution() override;
    double getSolution(int i) override;

    double getObjectiveValue() override;

    void updateVariableLowerBound(int variableIndex, double bound) override;
    void updateVariableUpperBound(int variableIndex, double bound) override;

    std::string getSolverDescription() override;

    // Updates a setting of the nested solver, also in the nested solvers created for later solves. A setting updated
    // directly in solver only applies until the next solve.
    void updateSetting(const std::string& name, int value);
    void updateSetting(const std::string& name, double value);
    void updateSetting(const std::string& name, bool value);

    // The nested solver of the latest solve
    std::shared_ptr<Solver> solver;

    // Whether hyperplanes generated by the nested solver are added to the main dual problem after each solve
    bool reuseHyperplanes = true;

    // Whether the cutoff from the best known solution of the main problem is used, which is not valid if the problem
    // solved has another objective function
    bool useCutOff = true;

protected:
    E_NLPSolutionStatus solveProblemInstance() override;

    VectorDouble getVariableLowerBounds() override;
    VectorDouble getVariableUpperBounds() override;
};
} // namespace SHOT